-- The postgres image runs that folder ONLY when the data directory is
-- empty, i.e. the first time the named volume korra_pgdata is used.
-- After that the volume already holds a database and this file is
-- skipped, so the seed rows are never inserted twice and records saved
-- by Korra are never overwritten.
